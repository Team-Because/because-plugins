# .venv/bin/python tools/mix.py <video-dir> [--dur <s>]
# Voice over music for a film: the music ducks 9 dB per LINE (gaps under 0.35 s held, 80 ms down, 400 ms back up), never
# per word: a per-word duck made the bed jump up and down inside every line (138 fast gain jumps, heard as glitches,
# 15-10-2026). Reads vo.wav (optional) and music.wav from the video folder. Writes mix.wav and, when vo.json exists, vo.js
# (const VO = word timings, for captions).
import os, sys, json
import numpy as np, soundfile as sf, librosa
vd = sys.argv[1]; SR = 44100
dur = float(sys.argv[sys.argv.index('--dur') + 1]) if '--dur' in sys.argv else None
mu, _ = librosa.load(os.path.join(vd, 'music.wav'), sr=SR, mono=True)
N = int((dur or len(mu) / SR) * SR); mu = np.pad(mu, (0, max(0, N - len(mu))))[:N]; mu /= np.abs(mu).max() + 1e-9
if os.path.exists(os.path.join(vd, 'vo.wav')):
    vo, _ = librosa.load(os.path.join(vd, 'vo.wav'), sr=SR, mono=True); vo = np.pad(vo, (0, max(0, N - len(vo))))[:N]; vo /= np.abs(vo).max() + 1e-9
    hop = int(0.01 * SR); act = np.array([(np.abs(vo[i:i + hop]) > 0.02).any() for i in range(0, N, hop)])
    idx = np.where(act)[0]
    for a, b in zip(idx[:-1], idx[1:]):
        if 1 < b - a <= 35: act[a:b] = True
    g = np.zeros(len(act))
    for i in range(1, len(act)): g[i] = g[i - 1] + ((1.0 if act[i] else 0.0) - g[i - 1]) * (0.125 if act[i] else 0.025)
    duck = 10 ** (-9 * np.repeat(g, hop)[:N] / 20)
    mix = vo * 0.9 + mu * 0.42 * duck
else:
    mix = mu * 0.9
mix /= np.abs(mix).max() / 0.89
sf.write(os.path.join(vd, 'mix.wav'), mix.astype(np.float32), SR)
if os.path.exists(os.path.join(vd, 'vo.json')):
    open(os.path.join(vd, 'vo.js'), 'w').write('// generated by tools/mix.py, do not edit by hand\nconst VO = ' + open(os.path.join(vd, 'vo.json')).read() + ';\n')
print('wrote mix.wav' + (' and vo.js' if os.path.exists(os.path.join(vd, 'vo.json')) else ''))
